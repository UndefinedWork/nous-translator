import AppKit
import ApplicationServices

/// Safely snapshots and restores pasteboard contents with a memory budget and transient markers.
enum SelectionClipboardSnapshot {
    static let maxSnapshotBytes = 8 * 1024 * 1024
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Captures pasteboard item representations up to `maxBytes`.
    /// Returns nil when the clipboard holds oversized objects so Copy fallback won't freeze the UI
    /// or risk dropping large promised data (e.g., Keynote/Photoshop/Excel payloads).
    static func capture(from items: [[(NSPasteboard.PasteboardType, () -> Data?)]], maxBytes: Int = maxSnapshotBytes) -> [[(NSPasteboard.PasteboardType, Data)]]? {
        var totalBytes = 0
        var snapshot: [[(NSPasteboard.PasteboardType, Data)]] = []
        for item in items {
            var entries: [(NSPasteboard.PasteboardType, Data)] = []
            for (type, reader) in item {
                // Avoid triggering lazy cross-process file promises that can materialize huge payloads.
                if type.rawValue.contains("FilePromise") || type.rawValue.contains("promise") {
                    return nil
                }
                guard let data = reader() else { continue }
                totalBytes += data.count
                if totalBytes > maxBytes { return nil }
                entries.append((type, data))
            }
            snapshot.append(entries)
        }
        return snapshot
    }

    /// Ensures restored clipboard items carry transient markers so clipboard managers ignore automated restores.
    static func withTransientMarkers(_ entries: [(NSPasteboard.PasteboardType, Data)]) -> [(NSPasteboard.PasteboardType, Data)] {
        var result = entries
        if !result.contains(where: { $0.0 == transientType }) {
            result.append((transientType, Data()))
        }
        if !result.contains(where: { $0.0 == autoGeneratedType }) {
            result.append((autoGeneratedType, Data()))
        }
        return result
    }
}

/// Reads the text a gesture selected in another app.
/// Accessibility first; Chromium/Electron and web views that expose nothing fall back to a
/// generated ⌘C, restoring the previous pasteboard only while its Copy result remains identifiable.
@MainActor enum SelectionCapture {
    private static let iBeam = NSCursor.iBeam.image.tiffRepresentation
    private static let verticalIBeam = NSCursor.iBeamCursorForVerticalLayout.image.tiffRepresentation
    private static var copying = false

    static var pointerIsIBeam: Bool {
        guard let current = NSCursor.currentSystem?.image.tiffRepresentation else { return false }
        return current == iBeam || current == verticalIBeam
    }

    /// Copy is serialized so rapid selections cannot restore one another's pasteboard snapshots.
    /// A cancelled read drains the pending copy, but never consumes or overwrites a newer user action.
    static func copySelection(pid: pid_t, mode: SelectionCopyMode = .menuOrKeyboard, isCurrent: () -> Bool) async -> String? {
        // A previous cancelled gesture may still be draining an asynchronous browser Copy.
        // Wait for it rather than making the next valid selection fail intermittently.
        for _ in 0..<65 where copying {
            do { try await Task.sleep(nanoseconds: 20_000_000) } catch { return nil }
            guard isCurrent() else { return nil }
        }
        guard !copying, !Task.isCancelled, isCurrent() else { return nil }
        copying = true
        defer { copying = false }
        let command = await SelectionAccessibilityReader.shared.copyCommand(pid: pid, targetOnly: mode == .menuOnly)
        guard !Task.isCancelled, isCurrent(),
              NSWorkspace.shared.frontmostApplication?.processIdentifier == pid else { return nil }
        if case .disabled = command { return nil }
        if mode == .menuOnly {
            guard case .enabled = command else { return nil }
        }
        let pasteboard = NSPasteboard.general
        let before = pasteboard.changeCount
        let readers: [[(NSPasteboard.PasteboardType, () -> Data?)]] = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.map { type in (type, { item.data(forType: type) }) }
        }
        // Abort Copy fallback rather than freezing the main thread or clobbering huge promised objects.
        guard let saved = SelectionClipboardSnapshot.capture(from: readers) else { return nil }
        guard pasteboard.changeCount == before, isCurrent() else { return nil }
        let performed = mode.perform(pressMenu: {
            guard case let .enabled(menu) = command else { return false }
            return AXUIElementPerformAction(menu, kAXPressAction as CFString) == .success
        }, postKeyboard: {
            guard CGPreflightPostEventAccess(), isCurrent(),
                  let source = CGEventSource(stateID: .combinedSessionState),
                  let down = CGEvent(keyboardEventSource: source, virtualKey: 8, keyDown: true),
                  let up = CGEvent(keyboardEventSource: source, virtualKey: 8, keyDown: false) else { return false }
            down.flags = .maskCommand; up.flags = .maskCommand
            TelosKeyboardEvent.markSynthetic(down); TelosKeyboardEvent.markSynthetic(up)
            down.postToPid(pid); up.postToPid(pid)
            return true
        })
        guard performed else { return nil }
        return await SelectionClipboardTransaction.finishCopy(initialChangeCount: before,
            isCurrent: isCurrent, changeCount: { pasteboard.changeCount },
            readText: { pasteboard.string(forType: .string) }, restore: {
                pasteboard.clearContents()
                let items = saved.map { entries in
                    let item = NSPasteboardItem()
                    for (type, data) in SelectionClipboardSnapshot.withTransientMarkers(entries) {
                        item.setData(data, forType: type)
                    }
                    return item
                }
                if !items.isEmpty { pasteboard.writeObjects(items) }
            })
    }
}
